pub fn decode_text(text: &str) -> String {
    let table: Vec<char> = CHARSET.chars().collect();
    text.chars()
        .map(|ch| {
            let code = ch as u32;
            if code < START {
                return ch;
            }
            match table.get((code - START) as usize) {
                Some(&c) if c != '_' => c,
                _ => ch,
            }
        })
        .collect()
}
